create or replace view px_projects2_vl
as
with n_tl as (
  select /*+ no_merge */ p.id
       , t.lang
       , t.tl
    from px_projects2 p
       , json_table(p.name_jtl, '$[*]'
          columns (
                   lang varchar2(10) path '$.l'
                 , tl   varchar2(50 char) path '$.tl'
                  )
        ) t
),
d_tl as (
  select /*+ no_merge */ p.id
       , t.lang
       , t.tl
    from px_projects2 p
       , json_table(p.description_jtl, '$[*]'
          columns (
                   lang varchar2(10) path '$.l'
                 , tl   varchar2(1000 char) path '$.tl'
                  )
        ) t
)
select p.id
     , p.name_jtl
     , p.description_jtl
     , n_tl.lang
     , n_tl.tl   name
     , d_tl.tl   description
     , p.alias
     , p.active_ind
     , p.created_by
     , p.created_on
     , p.updated_by
     , p.updated_on
  from px_projects2 p
     , n_tl
     , d_tl
 where p.id = n_tl.id
   and p.id = d_tl.id
   and n_tl.lang = d_tl.lang
   and n_tl.lang = (select nvl(apex_util.get_session_lang,'en') from dual)
/

